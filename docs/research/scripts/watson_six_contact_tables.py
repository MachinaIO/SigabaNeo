#!/usr/bin/env python3
"""Emit the contact geometry linking each pruned Boolean proof to its perfect form."""
import argparse
from fractions import Fraction
from itertools import combinations_with_replacement
import json
from pathlib import Path

from watson_six_resolution import balanced, expand, named_table


def vec(entries):
    return '!['+','.join(map(str,entries))+']'


def mat(rows):
    return '!!['+'; '.join(','.join(map(str,row)) for row in rows)+']'


def inverse(g):
    size=len(g)
    arr=[[Fraction(x) for x in row]+[Fraction(i==j) for j in range(size)]
         for i,row in enumerate(g)]
    for col in range(size):
        pivot=next(i for i in range(col,size) if arr[i][col])
        arr[col],arr[pivot]=arr[pivot],arr[col]
        a=arr[col][col]
        arr[col]=[x/a for x in arr[col]]
        for j,row in enumerate(arr):
            if j!=col:
                arr[j]=[u-row[col]*v for u,v in zip(row,arr[col],strict=True)]
    assert all(x.denominator==1 for row in arr for x in row[size:])
    return [[int(x) for x in row[size:]] for row in arr]


def emit(k,directory,output,rank=6):
    data=json.loads((directory/f'support{k}.json').read_text())
    if rank not in (6, 7):
        raise ValueError("supported ranks are 6 and 7")
    seven = rank == 7
    rank_name = 'Seven' if seven else 'Six'
    dim = rank*(rank+1)//2
    target = f'(Local.cone {k})' if seven else str(k)
    used, _, _=expand(data['clauses'],(directory/f'support{k}.lrat').read_text())
    z,gens,perms,rows,seeds=[data[x] for x in ('contacts','generators','permutations','relations','raySeeds')]
    selected=[data['reasons'][i] for i in used]
    relations=sorted({r[1] for r in selected if r[0]=='relation'})
    reason_index={v:i for i,v in enumerate(relations)}
    pairs=list(combinations_with_replacement(range(rank),2))
    m=len(z)
    namespace=f'SigabaNeo.Wall1.Watson.HigherGram.{rank_name}.Certificate{k}'
    lines=[f'import SigabaNeo.Lib.Lattices.Research.Wall1.Watson{rank_name}Resolution{k}',
           'import SigabaNeo.Lib.Lattices.Research.Wall1.' + ('WatsonSevenSupport' if seven else 'WatsonSupportClauses'),'',
           '/-! Integral contact and support witnesses generated by watson_six_contact_tables.py. -/',
           'noncomputable section',f'namespace {namespace}','open Finset Matrix MaskResolution',
           'set_option maxRecDepth 8192','set_option maxHeartbeats 10000000',
           f'def Z : Lines {m} := '+vec(map(vec,z))]
    if seven:
        lines.insert(lines.index('open Finset Matrix MaskResolution')+1, 'open ContactCone Local')
        lines.insert(lines.index('open ContactCone Local')+1, 'open Six (Reason usable)')
    def decl(name,statement,proof='by decide +kernel'):
        lines.extend(['',f'private theorem {name} : {statement} := {proof}'])
    lines+=['',f'theorem tight : ∀ i, Z i ≠ 0 ∧ value (representative {k}) (Z i) = 1 :=',
            (f'  fun i ↦ tight_of_rat (Z i) ((by decide +kernel : ∀ j, (fun a ↦ (Z j a : ℚ)) ⬝ᵥ (forms {k} *ᵥ fun a ↦ (Z j a : ℚ)) = 1) i)' if seven else f'  tight_of_rational {k} Z (by decide +kernel) (by decide +kernel)')]
    # Rows of twice the scaled inverse give the symmetric matrix units.
    weights=[]
    for v in data['inverse']:
        a=[0]*m
        for i,x in zip(data['basis'],v,strict=True):
            a[i]=2*x
        weights.append(a)
    lines+=['',f'private def coeff : Fin {dim} → Fin {m} → ℤ := '+vec(map(vec,weights)),
            f'private def lookup : Fin {rank} → Fin {rank} → Fin {dim} := '+
              vec(vec(pairs.index(tuple(sorted((i,j)))) for j in range(rank)) for i in range(rank)),
            f'private def w (a b : Fin {rank}) := coeff (lookup a b)']
    # Diagonal and off-diagonal pairs share the same recovery witness.
    for i in range(rank):
        decl(f'mom{i}',f'∀ b x y, moment Z (w {i} b) x y = {data["scale"]} * (picked {i} b x y + picked b {i} x y)')
    lines+=['',f'theorem separates : ∀ D, D.IsHermitian → (∀ i, contact (Z i) D = 0) → D = 0 := by',
            f'  apply separates_of_moments Z {data["scale"]} (by decide) w',
            '  intro a; fin_cases a']
    lines += [f'  · exact mom{i}' for i in range(rank)]
    realized = 'Local.realized' if seven else 'realized_perm'
    for i,(g,p) in enumerate(zip(gens,perms,strict=True)):
        ip=[p.index(j) for j in range(m)]
        lines+=['',f'private def perm{i} : Equiv.Perm (Fin {m}) :=',
                f'  ⟨{vec(p)},{vec(ip)},by decide +kernel,by decide +kernel⟩',
                f'private def auto{i} : IntMat := {mat(g)}',
                f'private def inv{i} : IntMat := {mat(inverse(g))}']
        decl(f'validPerm{i}',f'Realizes {target} Z perm{i}',
             f'by\n  apply {realized} perm{i} auto{i} inv{i}\n  · ext a b; fin_cases a <;> fin_cases b <;> decide +kernel\n  · ext a b; fin_cases a <;> fin_cases b <;> decide +kernel\n  · decide +kernel')
    lines += ['',f'private def perms : Fin {len(gens)} → Equiv.Perm (Fin {m}) := '+
                vec(f'perm{i}' for i in range(len(gens)))]
    decl('autocert',f'∀ i, Realizes {target} Z (perms i)','by\n  intro i; fin_cases i\n'+
         '\n'.join(f'  · exact validPerm{i}' for i in range(len(gens))))
    if relations:
        lines+=['',f'private def rows : Fin {len(relations)} → Fin {m} → ℤ := '+
                vec(vec(rows[v]) for v in relations)]
    else:
        lines+=['',f'private def rows : Fin 0 → Fin {m} → ℤ := Fin.elim0']
    for i in range(len(relations)):
        decl(f'rel{i}',f'∀ a b, moment Z (rows {i}) a b = 0')
    decl('relcert','∀ i a b, moment Z (rows i) a b = 0',
         ('by\n  intro i; fin_cases i\n'+'\n'.join(f'  · exact rel{i}' for i in range(len(relations)))) if relations else 'fun i ↦ i.elim0')
    def value(seed,v):
        return sum(a*v[i]*v[j]*(1 if i==j else 2) for a,(i,j) in zip(seed,pairs,strict=True))
    vals=[[value(seed,v) for v in z] for seed in seeds]
    first=0 if seven else sum(len(json.loads((directory/f'support{j}.json').read_text())['raySeeds']) for j in range(k))
    lines+=['',f'private def values : Fin {len(seeds)} → Fin {m} → ℤ := '+vec(map(vec,vals))]
    for j in range(len(seeds)):
        seed_index = f'⟨{j}, by decide +kernel⟩' if seven else str(first+j)
        src_check = '' if seven else '\n  · decide +kernel'
        decl(f'seed{j}',f'SeedValid {target} Z (values {j})',
             f'by\n  apply seedValid_of_pivot Z (values {j}) {seed_index}{src_check}\n  · ext a b; fin_cases a <;> fin_cases b <;> decide +kernel\n  · decide +kernel\n  · decide +kernel\n  · decide +kernel')
    decl('seedcert',f'∀ i, SeedValid {target} Z (values i)','by\n  intro i; fin_cases i\n'+
         '\n'.join(f'  · exact seed{j}' for j in range(len(seeds))))
    reasons=[]
    def word(xs): return '['+','.join(map(str,xs))+']'
    for name,*args in selected:
        if name=='nonzero':
            term='.nonzero'
        elif name=='ray':
            seed,w=args
            term=f'.ray {seed} {word(w)}'
        elif name=='symmetry':
            term=f'.symmetry {word(args[0])}'
        else:
            a,i=args
            term=f'.relation {reason_index[a]} {"true" if rows[a][i]<0 else "false"} {i}'
        reasons.append(term)
    lines+=['',f'private def reason : ℕ → Reason {m} {len(gens)} {len(relations)} {len(seeds)} := '+balanced(reasons)]
    pred='fun i ↦ usable perms rows values (bank i) (reason i)'
    if len(reasons)>400:
        lines.pop()
        lines+=named_table('reason',f'Reason {m} {len(gens)} {len(relations)} {len(seeds)}',reasons)
    checks=[]
    for a in range(0,len(used),8):
        n=min(8,len(used)-a)
        name=f'inputs{a}'
        decl(name,f'∀ j : Fin {n}, usable perms rows values (bank ({a}+j.val)) (reason ({a}+j.val))')
        checks.append((a,n,name))
    def join(xs):
        if len(xs)==1:
            return xs[0]
        mid=len(xs)//2
        a,n,left=join(xs[:mid])
        _,r,right=join(xs[mid:])
        name=f'inputs{a}to{a+n+r}'
        decl(name,f'∀ j : Fin {n+r}, usable perms rows values (bank ({a}+j.val)) (reason ({a}+j.val))',
             f'splitCheck (P := {pred}) {a} {n} {r} {left} {right}')
        return a,n+r,name
    _,_,root=join(checks)
    lines+=['',f'theorem normal : NormalSupport {target} Z :=',
            f'  normal_of_clauses Z perms rows values autocert relcert seedcert bank reason',
            f'    (by simpa using {root}) unsat','',f'end {namespace}','',
            f'#print axioms {namespace}.tight',f'#print axioms {namespace}.separates',f'#print axioms {namespace}.normal','']
    if seven:
        i = lines.index(f'end {namespace}')
        lines[i:i] = [f'theorem coverage : RayCoverageAt {k} := Local.coverage Z tight separates normal', '']
        lines = [line.replace('moment Z', 'ContactCone.moment Z').replace('picked ', 'ContactCone.picked ') for line in lines]
    (output/f'Watson{rank_name}Contacts{k}.lean').write_text('\n'.join(lines))


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('directory',type=Path)
    p.add_argument('output',type=Path)
    p.add_argument('--form',type=int,choices=range(7),action='append')
    a=p.parse_args()
    for k in range(7) if a.form is None else a.form:
        emit(k,a.directory,a.output)
