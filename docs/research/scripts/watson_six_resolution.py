#!/usr/bin/env python3
"""Expand the seven RUP certificates into binary-resolution proofs, pruning unused nodes."""
import argparse
import json
from pathlib import Path


def expand(clauses, lrat):
    bank = [frozenset(c) for c in clauses]
    origins = {i + 1: i for i in range(len(bank))}
    steps = {}
    cache = {c: i for i, c in enumerate(bank)}

    def add(left, right, bit, clause):
        if clause in cache:
            return cache[clause]
        index = len(bank)
        steps[index] = (left, right, bit)
        bank.append(clause)
        cache[clause] = index
        return index

    for row in lrat.splitlines():
        fields = row.split()
        if fields[1] == 'd':
            continue
        ident, *literals = map(int, fields)
        split = literals.index(0)
        goal = frozenset(literals[:split])
        assigned = {-x for x in goal}
        units = []
        for hint in literals[split+1:-1]:
            index = origins[hint]
            parent = bank[index]
            assert not parent & assigned
            unknown = [v for v in parent if -v not in assigned]
            if not unknown:
                break
            literal, = unknown
            units.append((literal, index))
            assigned.add(literal)
        else:
            raise ValueError(f'missing conflict in step {ident}')
        for literal, reason in reversed(units):
            if -literal not in bank[index]:
                continue
            left, right = (reason, index) if literal > 0 else (index, reason)
            pivot = abs(literal)
            result = (bank[left]-{pivot}) | (bank[right]-{-pivot})
            index = add(left, right, pivot-1, result)
        assert bank[index] <= goal
        if bank[index] != goal:
            index = add(index, index, 0, goal)
        origins[ident] = index
    assert bank[index] == frozenset()
    needed = {index}
    for i in reversed(range(len(clauses), len(bank))):
        if i in needed:
            needed.update(steps[i][:2])
    used = sorted(needed)
    positions = {v:i for i,v in enumerate(used)}
    return ([v for v in used if v<len(clauses)], [bank[v] for v in used],
            [(positions[steps[v][0]],positions[steps[v][1]],steps[v][2])
             for v in used if v in steps])


def masks(clause):
    return (sum(1<<(x-1) for x in clause if x>0),sum(1<<(-x-1) for x in clause if x<0))


def balanced(values, width=16):
    """A reducible table. Each kernel lookup follows a logarithmic number of branches."""
    if len(values) <= width:
        return '(fun i => (#['+','.join(values)+'])[i]?.getD default)'
    half=len(values)//2
    return (f'(fun i => if i < {half} then {balanced(values[:half],width)} i '
            f'else {balanced(values[half:],width)} (i-{half}))')


def named_table(name, typ, values, public=False):
    """Separate large tables at declaration boundaries to bound elaboration cost."""
    lines=[]
    def subtree(v, start, top=False):
        prefix='' if top and public else 'private '
        label=name if top else f'{name}At{start}Size{len(v)}'
        if len(v)<=160:
            body=balanced(v)
        else:
            n=len(v)//2
            left=subtree(v[:n],start)
            right=subtree(v[n:],start+n)
            body=f'fun i ↦ if i < {n} then {left} i else {right} (i-{n})'
        lines.append(f'{prefix}def {label} : ℕ → {typ} := {body}')
        return label
    subtree(values,0,True)
    return lines


def emit(k, directory, output, rank_name="Six"):
    data=json.loads((directory/f'support{k}.json').read_text())
    initial, bank, steps=expand(data['clauses'], (directory/f'support{k}.lrat').read_text())
    print(f'form {k}: {len(initial)} input clauses; {len(steps)} resolution steps')
    if output is None:
        return
    def struct(xs): return '⟨'+','.join(map(str,xs))+'⟩'
    namespace=f'SigabaNeo.Wall1.Watson.HigherGram.{rank_name}.Certificate{k}'
    length=len(steps)
    inputs=len(initial)
    lines=['import SigabaNeo.Lib.Lattices.Research.Wall1.WatsonMaskResolution','',
           '/-! Pruned resolution DAG generated by docs/research/scripts/watson_six_resolution.py. -/',
           f'namespace {namespace}', 'open SigabaNeo.Wall1.Watson.MaskResolution',
           'set_option maxRecDepth 8192','set_option maxHeartbeats 10000000','',
           f'def source : ℕ → ℕ := {balanced(list(map(str,initial)))}',
           f'def bank : ℕ → Clause := {balanced([struct(masks(c)) for c in bank])}',
           f'private def proof : ℕ → Step := {balanced([struct(s) for s in steps])}','']
    if len(bank)>1500:
        lines=lines[:lines.index(next(x for x in lines if x.startswith('def source')))]
        lines+=named_table('source','ℕ',list(map(str,initial)),True)
        lines+=named_table('bank','Clause',[struct(masks(c)) for c in bank],True)
        lines+=named_table('proof','Step',[struct(v) for v in steps])
        lines.append('')
    checks = []
    # A succession of short intervals makes certificate verification incremental.
    for a in range(0,length,32):
        num=min(32,length-a)
        name=f'checks{a}'
        lines += [f'private theorem {name} : ∀ j : Fin {num}, check bank {inputs} proof ({a} + j.val) := by decide +kernel']
        checks.append((a,num,name))
    def join(items):
        if len(items) == 1:
            return items[0]
        middle=len(items)//2
        a,n,left=join(items[:middle])
        _,r,right=join(items[middle:])
        name=f'split{a}to{a+n+r}'
        lines.extend([f'private theorem {name} : ∀ j : Fin {n+r}, check bank {inputs} proof ({a}+j.val) :=',
                      f'  splitCheck (P := fun i ↦ check bank {inputs} proof i = true) {a} {n} {r} {left} {right}'])
        return a,n+r,name
    _,_,root=join(checks)
    lines += ['',f'theorem unsat {{m : ℕ}} (b : Fin m → Bool) : ¬ ∀ i : Fin {inputs}, (bank i.val).Sat b := by',
              f'  exact refute b bank {inputs} proof {length} (by simpa using {root}) (by rfl) (by decide)',
              f'end {namespace}','',f'#print axioms {namespace}.unsat','']
    (output/f'Watson{rank_name}Resolution{k}.lean').write_text('\n'.join(lines))


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('directory',type=Path)
    p.add_argument('--lean-directory',type=Path)
    p.add_argument('--form',type=int,choices=range(7),action='append')
    a=p.parse_args()
    for k in range(7) if a.form is None else a.form:
        emit(k,a.directory,a.lean_directory)
