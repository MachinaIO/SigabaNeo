"""Generate contact-coordinate reconstructions for the simplicial rank-seven cones."""
import argparse
from collections import deque
from math import lcm
from pathlib import Path

from watson_seven_pivots import NS, literal, pari, ray_orbits, read_forms


def certificate(k, form):
    short = list(form.qfminim()[2])
    assert len(short) == 28
    count, representatives = ray_orbits(form, form.qfminim()[2])
    assert count == len(short)
    group = form.qfauto()[1]
    images = {}
    for j, r in enumerate(representatives):
        pending = deque([(r, pari.matid(7))])
        while pending:
            a, s = pending.popleft()
            values = [int(z.Vec()*a*z) for z in short]
            i, = (i for i, value in enumerate(values) if value)
            if i in images:
                continue
            assert values[i] > 0 and s.mattranspose()*r*s == a
            images[i] = j, a, s, values[i]
            for g in group:
                pending.append((g.mattranspose()*a*g, s*g))
    assert len(images) == 28
    c = lcm(*(row[3] for row in images.values()))
    rows = []
    for i, z in enumerate(short):
        j, a, s, value = images[i]
        mult = 2*c//value
        coeff = literal(mult*a)
        vec = '![' + ','.join(map(str,z)) + ']'
        rows.append(f"""  {{ z := {vec}
    coeff := {coeff}
    tight := tight_of_rat _ (by decide +kernel)
    slope := slope_of_action ⟨{j}, by decide +kernel⟩
      {literal(s)}
      {literal(s**-1)}
      _ {mult} (by decide +kernel) (matrix_eq_of_entries _ _ (by decide +kernel))
      (matrix_eq_of_entries _ _ (by decide +kernel)) (matrix_eq_of_entries _ _ (by decide +kernel)) }}""")
    return c, ',\n'.join(rows)


def emit(folder):
    cases = []
    for k, (_, form) in enumerate(read_forms(folder)):
        if form.qfminim()[2].ncols() != 28:
            continue
        c, rows = certificate(k, form)
        cases.append(k)
        (folder/f'WatsonSevenSimplex{k}.lean').write_text(f"""import SigabaNeo.Lib.Lattices.Research.Wall1.WatsonSevenSimplex

/-! Contact-coordinate certificate generated by `watson_seven_simplices.py`. -/
namespace {NS}.Simplex{k}
set_option maxRecDepth 16384
set_option maxHeartbeats 8000000

private def rows : Fin 28 → SimplexAtom {k} := ![
{rows}]

theorem coverage : RayCoverageAt {k} := by
  apply coverage_of_simplex rows {c} (by decide +kernel)
  decide +kernel

end {NS}.Simplex{k}
""")
    return cases


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('folder', type=Path)
    args = parser.parse_args()
    print(emit(args.folder))
