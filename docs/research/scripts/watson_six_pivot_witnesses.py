"""Produce the 32 rational pivot identities in WatsonSixPivotWitnesses.lean.

Run under the Sage Python environment with pplpy and cypari2, passing the desired
output path. The form table is read from Lean. The ray direction in each identity
is primitive and oriented into the cone. The target is given in an integral basis,
with an explicit integral inverse.
"""

import argparse
from pathlib import Path
from fractions import Fraction

from watson_perfect_neighbors import pari, matrix, pd, ray_orbits
from watson_six_marked_frames import lean_forms


def literal(a):
    return '!![' + '; '.join(','.join(map(str, row)) for row in a.python()) + ']'


def pivots():
    forms = [(m, pari.matrix(6, 6, entries)) for m, entries in lean_forms()]
    for k, (m, form) in enumerate(forms):
        count, rays = ray_orbits(form, form.qfminim()[2])
        print(f'form {k}: {count} rays, {len(rays)} orbit witnesses', flush=True)
        for r in rays:
            # All representatives are quarter-integral. Primitivity of r implies
            # that a congruent endpoint must occur at an integral quarter-step.
            steps = 1
            while True:
                end = (4 // m) * form + steps * r
                if not pd(end):
                    raise ValueError(f'no endpoint on ray at form {k}')
                for j, (mj, other) in enumerate(forms):
                    target = (4 // mj) * other
                    if end.matdet() != target.matdet():
                        continue
                    u = pari.qfisom(end, target)
                    if u != 0:
                        assert u.mattranspose() * target * u == end and abs(u.matdet()) == 1
                        assert (u**-1).denominator() == 1
                        break
                else:
                    steps += 1
                    continue
                yield f'⟨{k},{j},{steps},{literal(r)},{literal(u)},{literal(u**-1)}⟩'
                break


HEADER = """import SigabaNeo.Lib.Lattices.Research.Wall1.WatsonSixRepresentatives

/-! The 32 oriented pivot representatives of the rank-six walk. Directions are
primitive integral matrices. Steps are in quarters of the normalized Gram scale.
Generated by docs/research/scripts/watson_six_pivot_witnesses.py. -/

namespace SigabaNeo.Wall1.Watson.HigherGram.Six
open Matrix
abbrev IntMat := Matrix (Fin 6) (Fin 6) ℤ

structure PivotWitness where
  src : Fin 7
  dst : Fin 7
  quarters : ℕ
  direction : IntMat
  change : IntMat
  inverse : IntMat

def pivot : Fin 32 → PivotWitness :=
  !["""

FOOTER = """]

def qmat (A : IntMat) := A.map ((↑) : ℤ → ℚ)

set_option maxRecDepth 8192
set_option maxHeartbeats 8000000

/-- Verify the integer basis change and the complete endpoint matrix, entry by entry. -/
theorem pivot_identity (k : Fin 32) :
    let w := pivot k
    0 < w.quarters ∧ w.change * w.inverse = 1 ∧
    forms w.src + ((w.quarters : ℚ)/4) • qmat w.direction =
      (qmat w.change)ᵀ * forms w.dst * qmat w.change := by
  fin_cases k <;> refine ⟨by decide +kernel,Matrix.ext ?_,Matrix.ext ?_⟩ <;>
    intro i j <;> fin_cases i <;> fin_cases j <;> decide +kernel

/-- Every listed transition preserves the determinant under its integer change of basis. -/
theorem pivot_det (k : Fin 32) :
    let w := pivot k
    (forms w.src + ((w.quarters : ℚ)/4) • qmat w.direction).det = (forms w.dst).det := by
  obtain ⟨_,hinv,h⟩ := pivot_identity k
  let U := (pivot k).change
  have integral : IsUnit U.det :=
    isUnit_iff_exists_inv.mpr ⟨_,by simpa [U,det_mul] using congrArg det hinv⟩
  have unit : U.det = 1 ∨ U.det = -1 := Int.isUnit_iff.mp integral
  have castdet : (qmat U).det = (U.det : ℚ) := (Int.cast_det U).symm
  dsimp only
  rw [h,det_mul,det_mul,det_transpose]
  change (qmat U).det * _ * (qmat U).det = _
  rw [castdet]
  rcases unit with hU | hU <;> simp [hU]

end SigabaNeo.Wall1.Watson.HigherGram.Six

#print axioms SigabaNeo.Wall1.Watson.HigherGram.Six.pivot_identity
#print axioms SigabaNeo.Wall1.Watson.HigherGram.Six.pivot_det
"""

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    rows = list(pivots())
    assert len(rows) == 32
    args.output.write_text(HEADER + ',\n    '.join(rows) + FOOTER)
