"""Generate the integer witnesses in WatsonPivotData.lean (requires pplpy).

Each perturbed vertex gives ten active Gram tests and ten destinations. A bounded
edge connects two perturbation offsets. An unbounded edge gives a direction
toward another orbit point of the original polytope. Lean verifies the integer
data without invoking PPL or reasoning about infinitesimal parameters.
"""
from fractions import Fraction
from itertools import combinations, permutations, product
from math import lcm
from pathlib import Path
from random import Random
import re

import ppl

HERE = Path(__file__).resolve().parent
PAIRS = list(combinations(range(5), 2))
X = tuple(ppl.Variable(i) for i in range(10))


def dot(a, b):
    return sum(x*y for x, y in zip(a, b, strict=True))


def table():
    s = (HERE / "WatsonGramVertices.lean").read_text().split("def vertexEdges")[1].split("/--")[0]
    return [tuple(map(int, z.split(","))) for z in re.findall(r"!\[([-0-9,]+)\]", s)]


def tests():
    zs = list(product((-1, 0, 1), repeat=5))
    zs += [tuple(x*(2 if i == j else 1) for i,x in enumerate(z))
           for j in range(5) for z in product((-1,1), repeat=5)]
    return [(z, tuple(z[i]*z[j] for i,j in PAIRS), 2*(dot(z,z)-1))
            for z in zs if next((x for x in z if x),0)>0 and dot(z,z)>1]


def orbit(reps):
    images = {}
    for p in permutations(range(5)):
        perm = [PAIRS.index(tuple(sorted((p[i],p[j])))) for i,j in PAIRS]
        for tail in product((1,-1),repeat=4):
            s = (1,)+tail
            for k,r in enumerate(reps):
                key = tuple(r[t]*s[i]*s[j] for t,(i,j) in zip(perm,PAIRS,strict=True))
                images.setdefault(key,(k,p,s))
    return images


def arr(values):
    return "#[" + ",".join(map(str,values)) + "]"


def cert(k, vertex, images):
    constraints = tests()
    active = [(z, row) for z, row, c in constraints if c + dot(row, vertex) == 0]
    rows = [row for _, row in active]
    rng = Random(k)
    constants = [rng.randrange(3000) for _ in rows]
    poly = ppl.C_Polyhedron(10, "universe")
    for row, c in zip(rows, constants, strict=True):
        poly.add_constraint(dot(row, X) >= c)
    generators = poly.minimized_generators()
    rational_points = sorted(
        tuple(Fraction(g.coefficient(i), g.divisor()) for i in X)
        for g in generators if g.is_point()
    )
    scale = lcm(*(x.denominator for point in rational_points for x in point))
    points = [tuple(int(x * scale) for x in point) for point in rational_points]
    tight = [
        tuple(i for i, (row, c) in enumerate(zip(rows, constants, strict=True))
              if dot(row, point) == c * scale)
        for point in points
    ]
    assert all(len(basis) == 10 for basis in tight)
    faces = {}
    for j, basis in enumerate(tight):
        for i in basis:
            face = tuple(t for t in basis if t != i)
            faces.setdefault(face, []).append(j)
    rays = [tuple(int(g.coefficient(i)) for i in X) for g in generators if g.is_ray()]

    external = {}
    frames = []
    for j, basis in enumerate(tight):
        targets = []
        for i in basis:
            face = tuple(t for t in basis if t != i)
            adjacent = [index for index in faces[face] if index != j]
            if adjacent:
                target, = adjacent
                direction = tuple(y - x for x, y in zip(points[j], points[target], strict=True))
            else:
                direction, = [ray for ray in rays if all(dot(rows[h], ray) == 0 for h in face)]
                step = min(
                    Fraction(c + dot(row, vertex), -slope) for _, row, c in constraints
                    if (slope := dot(row, direction)) < 0
                )
                endpoint = tuple(x + step*y for x, y in zip(vertex, direction, strict=True))
                assert all(x.denominator == 1 for x in endpoint) and endpoint in images
                endpoint = tuple(map(int, endpoint))
                target = len(points) + external.setdefault(endpoint, len(external))
            assert dot(rows[i], direction) > 0 and all(dot(rows[h], direction) == 0 for h in face)
            targets.append(target)
        frames.append("⟨" + ",".join(map(arr, (points[j], basis, targets))) + "⟩")
    witnesses = []
    for endpoint in external:
        idx, perm, signs = images[endpoint]
        flips = arr("true" if x < 0 else "false" for x in signs)
        witnesses.append(f"⟨{arr(endpoint)},{idx},{arr(perm)},{flips}⟩")
    test_data = arr(arr(z) for z, _ in active)
    separator = ",\n    "
    return f"⟨{test_data},\n  #[\n    {separator.join(witnesses)}],\n  #[\n    {separator.join(frames)}]⟩"


def main():
    reps = table()
    images = orbit(reps)
    header = """import SigabaNeo.Lib.Lattices.Research.Wall1.WatsonPivot

/-! Integer witnesses generated by watson_pivot_certificate.py. -/
namespace SigabaNeo.Wall1.Watson.Pivot

"""
    code = [header,"def centers (k : Fin 24) : V := unpack (("+arr(map(arr,reps))+
            " : Array (Array ℤ))[k.val]?.getD #[])\n"]
    for k,v in enumerate(reps):
        code.append(f"def block{k} : Block :=\n  "+cert(k,v,images)+"\n")
    code.append("def blocks : Fin 24 → Block := !["+ ",".join(f"block{k}" for k in range(24))+"]\n")
    code.append("end SigabaNeo.Wall1.Watson.Pivot\n\n#print axioms SigabaNeo.Wall1.Watson.Pivot.blocks\n")
    (HERE/"WatsonPivotData.lean").write_text("\n".join(code))


if __name__ == "__main__":
    main()
