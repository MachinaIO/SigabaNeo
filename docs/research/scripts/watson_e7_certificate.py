"""Encode the E7 support refutation as kernel-checkable unit-propagation steps.

Bank indices and literals occupy 32 bits per hint. Each claim is proved in its
own interval of indices, so no single proof reduces the entire certificate.
"""
import argparse
import json
from pathlib import Path

from watson_six_resolution import masks, named_table

ROOT = 'SigabaNeo.Lib.Lattices.Research.Wall1.'
NS = 'SigabaNeo.Wall1.Watson.HigherGram.Seven.Certificate12'
PRELUDE = f'''namespace {NS}
open SigabaNeo.Wall1.Watson.MaskResolution
set_option maxRecDepth 16384
set_option maxHeartbeats 16000000
'''


def write_module(folder, name, imports, body):
    (folder/(name+'.lean')).write_text(''.join(f'import {ROOT}{x}\n' for x in imports) +
        '\n/-! Generated by watson_e7_certificate.py. -/\n' + PRELUDE + '\n' + body +
        f'\nend {NS}\n')


def table(name, values, group=1, width=0):
    if group == 1:
        packed = values
        label = name
    else:
        label = name + 'Blocks'
        packed = [sum(x << (width*j) for j,x in enumerate(values[i:i+group]))
                  for i in range(0,len(values),group)]
    lines = named_table(label, 'ℕ', ['0x'+format(x,'x') for x in packed], True)
    if group != 1:
        lines.append(f'def {name} (i : ℕ) : ℕ := ({label} (i / {group}) >>> '
                     f'({width} * (i % {group}))) % 2^{width}')
    return '\n'.join(lines)+'\n'


def join(items, pred, target):
    declarations = []
    def subtree(xs):
        if len(xs) == 1: return xs[0]
        mid=len(xs)//2
        a,n,l = subtree(xs[:mid])
        _,m,r = subtree(xs[mid:])
        name = f'{target}From{a}Size{n+m}'
        declarations.append(f'private theorem {name} : ∀ i : Fin {n+m}, {pred} ({a}+i.val) :=\n'
                            f'  splitCheck (P := fun j ↦ {pred} j) {a} {n} {m} {l} {r}')
        return a,n+m,name
    a,n,root = subtree(items)
    declarations.append(f'theorem {target} : ∀ i : Fin {n}, {pred} ({a}+i.val) := {root}')
    return '\n'.join(declarations)+'\n'


def checks(folder, stem, imports, pred, count, files, stride):
    intervals = []
    dependencies = []
    for piece in range(files):
        start = count*piece//files
        end = count*(piece+1)//files
        if end == start: continue
        module = stem+str(piece)
        dependencies.append(module)
        lines, spans = [], []
        for a in range(start,end,stride):
            n=min(stride,end-a)
            name=f'{stem}Check{a}'
            lines.append(f'private theorem {name} : ∀ i : Fin {n}, {pred} ({a}+i.val) := by decide +kernel')
            spans.append((a,n,name))
        label=f'{stem}Part{piece}'
        lines.append(join(spans,pred,label))
        intervals.append((start,end-start,label))
        write_module(folder,module,imports,'\n'.join(lines))
    return dependencies, join(intervals,pred,stem+'All')


def rup_data(clauses, lrat):
    bank={i+1:masks(c) for i,c in enumerate(clauses)}
    steps={}
    for line in lrat.splitlines():
        line=line.split()
        if line[1]=='d': continue
        row=list(map(int,line))
        stop=row.index(0)
        ident=row[0]
        pos,neg=masks(row[1:stop])
        bank[ident]=(pos,neg)
        signs=[]
        for hint in row[stop+1:-1]:
            hp,hn=bank[hint]
            p,n=hp & ~pos,hn & ~neg
            if p==n==0:
                signs.append((hint,127))
                break
            assert (p|n).bit_count()==1 and not (p and n)
            bit=(p|n).bit_length()-1
            signs.append((hint, bit if p else 64+bit))
            if p: neg |= p
            else: pos |= n
        assert signs[-1][1] == 127 and len(signs)<=64
        steps[ident]=signs
    assert bank[ident]==(0,0)
    needed={ident}
    for i in reversed(steps):
        if i in needed:
            needed.update(j for j,_ in steps[i])
    ids=sorted(needed)
    mapping={i:j for j,i in enumerate(ids)}
    used=[i-1 for i in ids if i<=len(clauses)]
    words=[sum(((mapping[j]<<7)|s)<<(32*h) for h,(j,s) in enumerate(steps[i]))
           for i in ids if i in steps]
    assert len(ids)<2**25
    return used,[p|(n<<63) for p,n in (bank[i] for i in ids)],words


def resolution(folder, used, bank, hints, files):
    write_module(folder,'WatsonE7RupBank',['WatsonMaskRup'],
                 table('clauseWord',bank,16,126)+
                 'def bank (i : ℕ) : Clause := ⟨clauseWord i % 2^63, clauseWord i >>> 63⟩\n')
    # Group offsets by chunks to avoid a single front-end pass over megabytes of proof integers.
    parts=[]
    def split(a,b):
        if b-a<=5000:
            name=f'WatsonE7Hints{a}'
            parts.append(name)
            write_module(folder,name,['WatsonMaskRup'],table(f'hints{a}',hints[a:b]))
            return f'hints{a}'
        m=(a+b)//2
        l,r=split(a,m),split(m,b)
        return f'(fun i ↦ if i < {m-a} then {l} i else {r} (i-{m-a}))'
    term=split(0,len(hints))
    write_module(folder,'WatsonE7Hints',parts,f'def hints : ℕ → ℕ := {term}\n')
    start=len(used)
    predicate=f'(rupCheck bank hints {start})'
    deps,all_checks=checks(folder,'WatsonE7Rup',['WatsonE7RupBank','WatsonE7Hints'],predicate,
                           len(hints),files,32)
    write_module(folder,'WatsonSevenResolution12',deps,all_checks+f'''
theorem unsat {{m : ℕ}} (b : Fin m → Bool) : ¬ ∀ i : Fin {start}, (bank i.val).Sat b :=
  refuteRup b bank hints {start} {len(hints)} (by simpa using WatsonE7RupAll)
    (by rfl) (by decide)
''')
    print(f'{start} input clauses and {len(hints)} RUP steps',flush=True)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('scratch',type=Path)
    parser.add_argument('folder',type=Path)
    args=parser.parse_args()
    data=json.loads((args.scratch/'support12.json').read_text())
    used,bank,hints=rup_data(data['clauses'],(args.scratch/'support12.lrat').read_text())
    resolution(args.folder,used,bank,hints,32)
    (args.scratch/'used12.json').write_text(json.dumps(used))
