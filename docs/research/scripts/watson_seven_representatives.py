"""Walk away from the E7 cone and emit rational LDL certificates for the discovered forms.

The omitted cone has 79,900,912 facets (Jaquet-Chiffelle, Ann. Inst. Fourier 43 (1993)).
This walk finds determinant witnesses. Its output does not assert classification in Lean.
"""
import argparse
from collections import deque
from fractions import Fraction
import json
from pathlib import Path

from watson_perfect_neighbors import matrix, neighbor, pari, primitive, ray_orbits


def collect(path):
    n=7
    first=matrix([[1+int(i==j) for j in range(n)] for i in range(n)])
    forms=[first]
    todo=deque([0])
    rows=[]
    while todo:
        i=todo.popleft()
        form=forms[i]
        _,minimum,short=pari.qfminim(form)
        minimum=int(minimum)
        q=Fraction(int(form.matdet()),minimum**7)
        record=dict(gram=form.python(),minimum=minimum,determinant=str(q),contacts=short.ncols())
        rows.append(record)
        if short.ncols()==63 and q==Fraction(1,64):
            # Its primitive integral dual is a separate seed. All its neighbors
            # can lie in the deliberately unexpanded E7 orbit.
            dual=form**-1
            end=primitive(dual.denominator()*dual)
            if not any(other.matdet()==end.matdet() and pari.qfisom(other,end)!=0 for other in forms):
                todo.append(len(forms))
                forms.append(end)
            print(f'{i}: E7 determinant {q}, tangent cone omitted, dual seeded',flush=True)
            continue
        count,directions=ray_orbits(form,short)
        neighbors=[]
        for direction in directions:
            end=neighbor(form,minimum,direction)
            j=next((k for k,b in enumerate(forms)
                    if b.matdet()==end.matdet() and pari.qfisom(b,end)!=0),None)
            if j is None:
                j=len(forms)
                forms.append(end)
                todo.append(j)
            neighbors.append(j)
        record.update(rays=count,neighbors=neighbors)
        print(f'{i}: {q}, contacts={short.ncols()}, rays={count}, orbits={len(directions)}, '
              f'discovered={len(forms)}',flush=True)
    path.write_text(json.dumps(rows,separators=(',',':'))+'\n')
    print(f'{len(rows)} forms, {sum(len(r.get("neighbors",[])) for r in rows)} oriented pivots '
          'outside E7',flush=True)


def upper_ldl(A):
    n=len(A)
    U=[[Fraction(int(i==j)) for j in range(n)] for i in range(n)]
    d=[]
    for j in range(n):
        d.append(A[j][j]-sum(d[i]*U[i][j]**2 for i in range(j)))
        assert d[-1]>0
        for t in range(j+1,n):
            U[j][t]=(A[j][t]-sum(d[i]*U[i][j]*U[i][t] for i in range(j)))/d[-1]
    return U,d


def emit(path,out):
    rows=json.loads(path.read_text())
    def vec(v): return '!['+','.join(map(str,v))+']'
    def mat(A): return '!!['+'; '.join(','.join(map(str,v)) for v in A)+']'
    ns='SigabaNeo.Wall1.Watson.HigherGram.Seven'
    lines=['import SigabaNeo.Lib.Lattices.Research.Wall1.WatsonHigherPolytope','',
           '/-! Exact determinants of the rank-seven forms reached by the walk outside E7.',
           'Generated by docs/research/scripts/watson_seven_representatives.py. -/',
           'noncomputable section',f'namespace {ns}','open Matrix Finset',
           'abbrev Q := Matrix (Fin 7) (Fin 7) ℚ','set_option maxRecDepth 8192',
           'set_option maxHeartbeats 8000000','']
    for k,r in enumerate(rows):
        A=[[Fraction(x,r['minimum']) for x in v] for v in r['gram']]
        U,d=upper_ldl(A)
        exact=Fraction(1)
        for x in d: exact*=x
        assert exact==Fraction(r['determinant']) and exact>=Fraction(1,64)
        lines.extend([f'private def gram{k} : Q := '+mat(A),
                      f'private def upper{k} : Q := '+mat(U),
                      f'private def diag{k} : Fin 7 → ℚ := '+vec(d)])
    n=len(rows)
    for name,typ,prefix in [('forms','Q','gram'),('upper','Q','upper'),('diag','Fin 7 → ℚ','diag')]:
        lines+=['',('' if name=='forms' else 'private ')+f'def {name} : Fin {n} → {typ} := '+
                vec(prefix+str(k) for k in range(n))]
    lines+=['',f'def detTable : Fin {n} → ℚ := '+vec(r['determinant'] for r in rows),
            f'def representative (k : Fin {n}) : Mat 7 := (forms k).map (Rat.castHom ℝ)']
    for k in range(n):
        lines.extend(['',f'private theorem factor{k} : gram{k} = upper{k}ᵀ * diagonal diag{k} * upper{k} := by',
                      '  ext i j; fin_cases i <;> fin_cases j <;> decide +kernel'])
    lines+=['',f'private theorem factors (k : Fin {n}) : forms k = (upper k)ᵀ * diagonal (diag k) * upper k := by','  fin_cases k']
    lines += [f'  · exact factor{k}' for k in range(n)]
    lines+=['', 'private theorem upper_tri : ∀ k i j, j < i → upper k i j = 0 := by',
            '  intro k i j; fin_cases k <;> fin_cases i <;> fin_cases j <;> decide +kernel',
            'private theorem upper_diag : ∀ k i, upper k i i = 1 := by decide +kernel',
            'private theorem piv_pos : ∀ k i, 0 < diag k i := by decide +kernel',
            'private theorem det_product : ∀ k, ∏ i, diag k i = detTable k := by decide +kernel',
            'private theorem floor_bound : ∀ k, (1:ℚ)/64 ≤ detTable k := by decide +kernel','',
            f'theorem representative_bound (k : Fin {n}) :','    (representative k).PosDef ∧ (representative k).det = (detTable k : ℝ) ∧',
            '    (1:ℝ)/64 ≤ (representative k).det := by',
            '  let U := upper k','  have tri : U.IsUpperTriangular := fun i j hij ↦ upper_tri k _ _ hij',
            '  have dU : U.det = 1 := by rw [det_of_isUpperTriangular tri]; simp [U,upper_diag]',
            '  let V := U.map (Rat.castHom ℝ)','  have dv : V.det = 1 := by',
            '    change ((Rat.castHom ℝ).mapMatrix U).det = _','    rw [← RingHom.map_det,dU,map_one]',
            '  have eq : representative k = Vᴴ * diagonal (fun i ↦ (diag k i : ℝ)) * V := by',
            '    simp only [representative,factors k,Matrix.map_mul,diagonal_map (map_zero _)]','    rfl',
            '  rw [eq]','  refine ⟨(posDef_diagonal_iff.mpr fun i ↦ (by exact_mod_cast piv_pos k i :',
            '    0 < (diag k i : ℝ))).conjTranspose_mul_mul_same',
            '      (mulVec_injective_of_isUnit ((Matrix.isUnit_iff_isUnit_det V).mpr (dv ▸ isUnit_one))),?_⟩',
            '  rw [det_mul,det_mul,det_conjTranspose,dv,star_one,one_mul,mul_one,det_diagonal]',
            '  constructor','  · exact_mod_cast det_product k',
            '  · have h := Rat.cast_le (K := ℝ) |>.mpr (floor_bound k)',
            '    rw [← det_product] at h','    push_cast at h','    linarith',
            '',f'end {ns}','',f'#print axioms {ns}.representative_bound','']
    out.write_text('\n'.join(lines))


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('data',type=Path)
    p.add_argument('--lean',type=Path)
    args=p.parse_args()
    if args.lean: emit(args.data,args.lean)
    else: collect(args.data)
